#!/usr/bin/env python3
"""Vendor a curated subset of Material Icon Theme (MIT) file/folder icons.

Writes crates/loft-ui/assets/file-icons/*.svg and
crates/loft-ui/src/file_icons_table.rs. Re-run to change the set:
    python3 xtask/scripts/file_icons.py
"""
import json, os, pathlib, urllib.request

VERSION = "5.40.0"
BASE = f"https://cdn.jsdelivr.net/npm/material-icon-theme@{VERSION}"
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_SVG = ROOT / "crates/loft-ui/assets/file-icons"
OUT_RS = ROOT / "crates/loft-ui/src/file_icons_table.rs"

# File icons worth shipping: languages, config, docs, media, tooling.
FILE_ICONS = """
rust typescript react_ts javascript react python markdown toml json lock swift go
java kotlin c cpp h hpp csharp ruby php html css sass less yaml xml svg image pdf
word powerpoint table zip console docker git license readme nodejs npm yarn pnpm
settings document log database graphql vue svelte astro lua zig elixir erlang
haskell scala dart r julia perl makefile cmake nix terraform prisma vite tailwindcss
eslint prettier babel webpack jest vitest tsconfig editorconfig tune certificate key
font audio video jupyter changelog contributing authors todo http proto webassembly
gradle maven cargo deno bun python-misc kubernetes nginx apple windows ocaml clojure
fsharp vim powershell objective-c groovy solidity coffee pug handlebars twig latex
diff caddy fortran assembly cuda verilog mdx storybook playwright cypress turborepo
netlify vercel firebase supabase docker-compose dotenv command bazel buck just
""".split()

FOLDERS = """
src source docs doc test tests __tests__ e2e assets images img icons .github .git
node_modules scripts config components lib dist build out public .vscode .idea
packages app api utils crates target examples bin vendor fixtures mocks styles css
hooks types server client i18n locales migrations database db fonts temp tmp logs
.cargo benches ios android web .claude tools include pkg cmd static templates views
models routes middleware plugins store services coverage .husky .devcontainer docker
k8s terraform proto layouts pages content data screenshots resources res xtask
""".split()


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read()


def main():
    manifest = json.loads(fetch(f"{BASE}/dist/material-icons.json"))
    defs = manifest["iconDefinitions"]
    icons = {i for i in FILE_ICONS if i in defs}
    icons |= {manifest["file"], manifest["folder"], manifest["folderExpanded"]}
    folder_map = {}
    for name in FOLDERS:
        icon = manifest["folderNames"].get(name)
        if icon and icon in defs and icon + "-open" in defs:
            folder_map[name] = icon
            icons |= {icon, icon + "-open"}
    ext_map = {e: i for e, i in manifest["fileExtensions"].items() if i in icons}
    name_map = {n: i for n, i in manifest["fileNames"].items() if i in icons}
    # Languages VS Code infers from the extension alone.
    for lang, ext in [("rust", "rs"), ("python", "py"), ("go", "go"), ("c", "c"),
                      ("cpp", "cpp"), ("javascript", "js"), ("typescript", "ts"),
                      ("java", "java"), ("ruby", "rb"), ("php", "php"), ("html", "html"),
                      ("css", "css"), ("yaml", "yml"), ("yaml", "yaml"), ("xml", "xml"),
                      ("markdown", "md"), ("json", "json"), ("swift", "swift"),
                      ("kotlin", "kt"), ("csharp", "cs"), ("lua", "lua"), ("dart", "dart"),
                      ("shellscript", "sh"), ("shellscript", "bash"), ("shellscript", "zsh"),
                      ("perl", "pl"), ("r", "r"), ("scala", "scala"), ("haskell", "hs"),
                      ("elixir", "ex"), ("erlang", "erl"), ("sql", "sql"), ("vue", "vue")]:
        icon = manifest["languageIds"].get(lang)
        if icon in icons:
            ext_map.setdefault(ext, icon)

    OUT_SVG.mkdir(parents=True, exist_ok=True)
    for old in OUT_SVG.glob("*.svg"):
        old.unlink()
    for icon in sorted(icons):
        path = defs[icon]["iconPath"].split("/icons/")[-1]
        (OUT_SVG / f"{icon}.svg").write_bytes(fetch(f"{BASE}/icons/{path}"))

    def table(name, pairs):
        rows = "\n".join(f'    ({json.dumps(k)}, {json.dumps(v)}),' for k, v in sorted(pairs.items()))
        return f"pub static {name}: &[(&str, &str)] = &[\n{rows}\n];\n"

    svgs = "\n".join(
        f'    ({json.dumps(i)}, include_bytes!("../assets/file-icons/{i}.svg")),'
        for i in sorted(icons)
    )
    OUT_RS.write_text(
        "// Generated by xtask/scripts/file_icons.py from Material Icon Theme "
        f"{VERSION} (MIT). Do not edit.\n\n"
        f"pub static SVGS: &[(&str, &[u8])] = &[\n{svgs}\n];\n\n"
        + table("EXTENSIONS", ext_map) + "\n"
        + table("FILE_NAMES", name_map) + "\n"
        + table("FOLDERS", folder_map)
    )
    total = sum(f.stat().st_size for f in OUT_SVG.glob("*.svg"))
    print(f"{len(icons)} icons ({total // 1024} KiB), {len(ext_map)} extensions, "
          f"{len(name_map)} file names, {len(folder_map)} folders")


if __name__ == "__main__":
    main()
